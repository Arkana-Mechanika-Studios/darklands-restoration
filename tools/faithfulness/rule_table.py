"""rule_table.py: writes src/Darklands.Core/RuleTable.Generated.cs from docs/faithfulness/switches.csv.

The fix flags of the switch register (rows of kind `flag`), in the CSV's order: each flag's index, register id, property of
OriginalBehaviour, class and the presets it is on in (the `presets` column). SwitchRegisterTests fails when the CSV and the
generated table differ; run this after changing a flag row:

    tools/python/Scripts/python.exe -I -B tools/faithfulness/rule_table.py

The presets column names the player's reference set `classic` (the name before 2026-11-24); it is the Original preset here.
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSV = os.path.join(ROOT, "docs", "faithfulness", "switches.csv")
OUT = os.path.join(ROOT, "src", "Darklands.Core", "RuleTable.Generated.cs")

# the presets column's words and the RulePreset each stands for
PRESETS = {"classic": "Original", "fixed": "Fixed", "restored": "Restored"}


def main():
    with open(CSV, encoding="utf-8", newline="") as f:
        rows = [r for r in csv.DictReader(f) if r["kind"] == "flag"]
    lines = [
        "// <auto-generated>",
        "// Generated from docs/faithfulness/switches.csv by tools/faithfulness/rule_table.py: do not edit by hand. SwitchRegisterTests",
        "//   compares this table with the CSV; run the script again after changing a flag row.",
        "// </auto-generated>",
        "// Not in the original: the rule table of the presets.",
        "namespace Darklands.Core;",
        "",
        "public static partial class RuleTable",
        "{",
    ]
    for i, r in enumerate(rows):
        lines.append(f"    /// <summary>The index of <c>{r['id']}</c> (<see cref=\"OriginalBehaviour.{r['key']}\"/>).</summary>")
        lines.append(f"    public const int {r['key']} = {i};")
        lines.append("")
    lines.append("    /// <summary>Every fix flag of the switch register, in its order (the index of each is its place here).</summary>")
    lines.append("    public static IReadOnlyList<Rule> Flags { get; } =")
    lines.append("    [")
    for r in rows:
        words = [w for w in r["presets"].split(";") if w]
        unknown = [w for w in words if w not in PRESETS]
        if unknown:
            sys.exit(f"{r['id']}: unknown preset {unknown}")
        on = [PRESETS[w] for w in words]
        lines.append(f"        new(\"{r['id']}\", nameof(OriginalBehaviour.{r['key']}), \"{r['class']}\", "
                     f"{str('Original' in on).lower()}, {str('Fixed' in on).lower()}, {str('Restored' in on).lower()}),")
    lines.append("    ];")
    lines.append("}")
    text = "\n".join(lines) + "\n"
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print(f"{len(rows)} flags -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
