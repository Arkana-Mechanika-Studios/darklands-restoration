"""Add generated sessions to rerun_all.SESSIONS: python -I -B add_sessions.py < lines (as gen_screen_sessions.py prints them)."""
import re
import sys
from pathlib import Path

p = Path(__file__).with_name("rerun_all.py")
s = p.read_text(encoding="utf-8")
marker = "# the sessions run with --battle-records"
have = set(re.findall(r'"(gen-[a-z0-9]+-\d+)":', s))
new = []
for l in sys.stdin.read().splitlines():
    m = re.match(r'"(gen-[a-z0-9]+-\d+)":', l)
    if m and m.group(1) not in have:
        new.append("            " + l.strip())
if new:
    i = s.index(marker)
    j = s.rindex("}", 0, i)
    block = ",\n            # generated by gen_screen_sessions.py (seeded key / mouse walks over one screen)\n" + "\n".join(new)
    block = block.rstrip(",")
    s = s[:j] + block + s[j:]
    p.write_text(s, encoding="utf-8")
print(len(new), "added")
