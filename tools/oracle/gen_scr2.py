"""Round scr2: scripted lockstep sessions aimed at the screens' open pointer regions and key sets (cut from existing sessions).

usage: python -I -B gen_scr2.py [recipe ...] --out DIR   (the kept sessions of round scr2 are in lockstep-sessions/)
"""
from __future__ import annotations

import argparse
import string
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_screen_sessions import cut  # noqa: E402

W = "wait:30"


def keys(seq, wait=W):
    out = []
    for k in seq:
        out += ["key:" + k, wait]
    return out


def clicks(xs, ys, wait="wait:60", move=False):
    out = []
    for y in ys:
        for x in xs:
            if move:
                out += ["move:%d,%d" % (x, y), "wait:10"]
            out += ["click:%d,%d" % (x, y), wait]
    return out


LETTERS = list(string.ascii_lowercase)
DIGITS = list("0123456789")


def r_camp(v):
    """The camp / stay screen's pointer regions (R036+0x0082: x 0xF5..0x13E, y 0x30..0x71) and the Save / Load / Quit-type edges."""
    out = cut("stay", "stay").splitlines()
    out += ["state:in"]
    if v == 1:
        out += clicks(range(0xF0, 0x142, 12), range(0x2C, 0x78, 8), move=True)
    elif v == 2:
        out += clicks(range(0xF5, 0x140, 20), range(0x30, 0x72, 5), move=False)
    else:
        out += clicks(range(0x10, 0xF0, 24), range(0x10, 0xC0, 20), move=True)
    out += ["state:clicked", "key:esc", "wait:300", "state:end"]
    return "Dksave10.sav", out


def r_pray(v):
    out = cut("saints", "saints").replace("key:f3", "key:f%d" % (1 + v % 5)).splitlines()
    out += ["click:100,%d" % (75 + 8 * (v % 4)), "wait:300", "state:saint"]
    if v == 1:
        out += clicks(range(150, 318, 24), range(142, 196, 6), move=True)
    elif v == 2:
        out += clicks(range(251, 310, 14), range(143, 192, 4), move=False)
    else:
        out += clicks(range(8, 318, 30), range(8, 196, 14), move=True)
    out += ["state:clicked", "key:esc", "wait:300", "state:end"]
    return "Dksave10.sav", out


def r_sheet(v):
    out = cut("sheet", "sheet").splitlines()
    if v == 1:
        out += keys(LETTERS) + ["state:letters"] + keys(DIGITS) + ["state:digits"]
    elif v == 2:
        out += clicks(range(10, 318, 26), range(8, 196, 16), move=True)
    else:
        out += keys(["f%d" % i for i in range(1, 11)], "wait:100") + keys(["tab", "up", "down", "left", "right", "home", "end", "pgup", "pgdn"]) + ["state:fk"]
        out += clicks(range(20, 318, 40), range(20, 196, 24), move=False)
    out += ["state:swept", "key:esc", "wait:300", "state:end"]
    return "Dksave10.sav", out


def r_create(v):
    """The generator's key sets: letters at the roster / generator page and the family page, digits, arrows."""
    out = cut("roster-create2", "generator").splitlines()
    if v == 1:
        out += keys(LETTERS) + ["state:letters"]
    elif v == 2:
        out += keys(DIGITS + ["up", "down", "left", "right", "tab", "home", "end", "pgup", "pgdn"]) + ["state:digits"]
    else:
        out += ["key:e", "wait:100"] + keys(list("abcdefghijklmnopqrstuvwx"), "wait:20") + ["key:enter", "wait:100", "state:longname"]
        out += ["key:c", "wait:100"] + keys(list("abcdefghijkl"), "wait:20") + ["key:enter", "wait:100", "state:nick"]
        out += keys(["m", "f", "m"]) + ["key:b", "wait:300", "state:family"] + keys(LETTERS[:13]) + ["state:fkeys"]
    out += ["key:esc", "wait:300", "state:end"]
    return "DKSAVE8.SAV", out


RECIPES = {}
for v in (1, 2, 3):
    RECIPES["camp-%d" % v] = (lambda v=v: r_camp(v))
    RECIPES["pray-%d" % v] = (lambda v=v: r_pray(v))
    RECIPES["sheet-%d" % v] = (lambda v=v: r_sheet(v))
    RECIPES["create-%d" % v] = (lambda v=v: r_create(v))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("recipes", nargs="*")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    Path(a.out).mkdir(parents=True, exist_ok=True)
    for r in a.recipes or sorted(RECIPES):
        save, lines = RECIPES[r]()
        name = "scr2-" + r
        (Path(a.out) / (name + ".steps")).write_text("# Generated by gen_scr2.py (%s)\n" % r + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        print('"%s": "%s",' % (name, save))




def r_pray2(v):
    """Round 2: other members and saint rows, finer box grid, M / L then the Pray line."""
    out = cut("saints", "saints").replace("key:f3", "key:f%d" % (1 + v % 5)).splitlines()
    out += ["click:100,%d" % (75 + 8 * (v % 8)), "wait:300", "state:saint"]
    if v % 3 == 0:
        out += keys(["m"] * (v % 5 + 1)) + ["move:200,175", "wait:10"] + clicks(range(255, 310, 18), range(144, 192, 3), move=True)
    elif v % 3 == 1:
        out += clicks(range(150, 318, 10), range(156, 194, 4), move=False)
        out += keys(["l", "l", "m"]) + ["click:200,175", "wait:200", "move:280,150", "wait:10", "click:280,150", "wait:200"]
    else:
        out += ["move:200,175", "wait:10"] + clicks([260, 290], range(143, 192, 2), move=True) + keys(["m", "l"]) + ["click:200,185", "wait:200"]
    out += ["state:clicked", "key:esc", "wait:300", "state:end"]
    return "Dksave10.sav", out


def r_create2(v):
    out = cut("roster-create2", "generator").splitlines()
    if v == 1:    # backspace and esc in the prompts
        out += ["key:e", "wait:100"] + keys(list("abc") + ["backspace"] * 5 + list("xy"), "wait:20") + ["key:esc", "wait:100", "state:esc-name"]
        out += ["key:e", "wait:100", "key:enter", "wait:100", "state:empty-name", "key:c", "wait:100", "key:esc", "wait:100", "state:esc-nick"]
        out += ["key:c", "wait:100", "key:enter", "wait:100"] + keys(["m", "f", "x", "n", "s", "tab"]) + ["state:sex"]
    elif v == 2:  # overlong name and nickname, then the family page keys
        out += ["key:e", "wait:100"] + keys(list("abcdefghijklmnopqrstuvwxyz"), "wait:20") + ["key:enter", "wait:100", "state:name"]
        out += ["key:c", "wait:100"] + keys(list("abcdefghijklmnop"), "wait:20") + ["key:backspace", "wait:20", "key:enter", "wait:100", "state:nick"]
        out += ["key:b", "wait:300", "state:family"] + keys(["up", "down", "enter", "esc", "space"]) + ["state:fam-keys"]
    else:         # sex toggles and the other roster keys at the generator page
        out += keys(["m", "f", "m", "f", "left", "right", "up", "down", "home", "end", "pgup", "pgdn", "tab", "space"]) + ["state:pagekeys"]
        out += ["key:e", "wait:100"] + keys(list("zed"), "wait:20") + ["key:enter", "wait:100", "key:c", "wait:100", "key:z", "wait:20", "key:enter", "wait:100", "state:named"]
        out += ["key:b", "wait:300", "state:family", "click:120,52", "wait:100", "state:childhood"] + keys(["up", "down", "left", "right", "enter", "space", "backspace", "tab"]) + ["state:childkeys"]
    out += ["key:esc", "wait:300", "state:end"]
    return "DKSAVE8.SAV", out


for v in range(4, 10):
    RECIPES["pray-%d" % v] = (lambda v=v: r_pray2(v))
for v in (4, 5, 6):
    RECIPES["create-%d" % v] = (lambda v=v: r_create2(v - 3))


if __name__ == "__main__":
    main()
