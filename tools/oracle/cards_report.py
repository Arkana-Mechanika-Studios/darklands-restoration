"""docs/faithfulness/CARDS.md from the card oracle's corpus, the C# replay and the branch coverage.

usage: python -I -B cards_report.py <cards-oracle.json.gz> <replay report.tsv> <branches.csv> <card-divergences.json> <out CARDS.md>

The replay report is what CardOracleTests writes with DARKLANDS_CARD_ORACLE_REPORT (card, function,
runs agreeing, runs differing for a listed reason, runs differing, first difference). The coverage is
block_coverage.py's branches.csv with the card oracle as a source: per card record (R044..R135) the
blocks and branch outcomes of all its functions.
"""
from __future__ import annotations

import collections
import csv
import gzip
import json
import sys
from pathlib import Path


def pct(a, b):
    return "%.1f%%" % (100.0 * a / b) if b else "-"


def main():
    corpus_path, report_path, branches_path, divergences_path, out = (Path(x) for x in sys.argv[1:6])
    corpus = json.load(gzip.open(corpus_path, "rt", encoding="utf-8"))
    replay = {}
    for line in report_path.read_text(encoding="utf-8").splitlines():
        p = line.split("\t")
        replay[p[0]] = {"agree": int(p[2]), "justified": int(p[3]), "differ": int(p[4]), "first": p[5] if len(p) > 5 else ""}
    cover = collections.defaultdict(lambda: [0, 0, 0, 0, 0])
    for r in csv.DictReader(branches_path.open(encoding="utf-8")):
        c = cover[r["record"]]
        c[0] += int(r["blocks_hit"])
        c[1] += int(r["blocks"])
        c[2] += int(r["outcomes_hit"])
        c[3] += int(r["outcomes"])
        c[4] += 1
    divergences = json.loads(divergences_path.read_text(encoding="utf-8")) if divergences_path.exists() else []
    cards = corpus["cards"]
    runs = sum(len(v["runs"]) for v in cards.values())
    stops = sum(1 for v in cards.values() for r in v["runs"].values() if not r["end"].startswith("next"))
    agree = sum(v["agree"] for v in replay.values())
    justified = sum(v["justified"] for v in replay.values())
    differ = sum(v["differ"] for v in replay.values())
    full = sum(1 for v in replay.values() if v["differ"] == 0)
    recs = sorted({v["record"] for v in cards.values()})
    rb = [sum(cover[r][k] for r in recs) for k in range(4)]
    L = ["# The card oracle: every card of the original against the C#", "",
         "Generated by `tools/oracle/cards_report.py` (do not edit by hand).", "",
         "`tools/oracle/card_oracle.py` runs each card function of the ORIGINAL DARKLAND.EXE (card table",
         "`R136+0xD090` -> its RTLink vector -> the card's record R044..R135) in a DOS machine",
         "(`tools/oracle/dosmachine.py`: the root, the data image, the card engine R043 and the rules R029 at",
         "their link-time addresses, the card's own record, every overlay call through its vector with the",
         "callers loaded back afterwards, the C run-time on a DOS emulation with the game folder's files).",
         "Each run starts from a state the C# exports (`CardOracleStates`: the golden traces' states, a",
         "Quickstart game with seed option + 7 at location 3 or 120) as the original's own saved game, which",
         "the original loads with its own loader (R037 1C7D:0D24) after its own world loader (R043 1462:0100);",
         "what a saved game does not hold (the random generator, the bankers, the working city record and",
         "description, the card engine's variables) is set as the C# has it.", "",
         "The rules, the card engine's logic (usable-item-list, saints-available, the text expansion), the R039/R030/",
         "R031 helpers and the CRT run from the original bytes. Stubbed: drawing and input (pictures, the party",
         "panel, text drawing, palette, mouse, keyboard), the menu (`card-choice-menu`: the golden traces' policy,",
         "options 0..9; probing, every offered line's hint is asked as Shift over it asks it, with",
         "menu-owner-member/menu-choice-index = line / 4, line % 4, and an item/saint line is chosen in its pop-up box), the",
         "hourglass, message boxes, the full screens (shop, camp, item store: recorded), the prayer screen",
         "(the prayer fails, as the C# without one) and battles (result 0, as the C# without a battle).",
         "`srand(time(0))` sees the machine's fixed DOS clock; the C# gets the same value as its ClockSeed.", "",
         "Each run records the trace (pictures, every text as the original's text-substitute gives it, menus with",
         "the states of the block's option lines, hints with chance, message and member, messages, time,",
         "screens, battles), the next card, the random generator and the bytes of the saved game the",
         "original's own writer (R037 1462:2ACE) makes afterwards that differ from the start.",
         "`tests/Darklands.Cards.Tests/Oracle/CardOracleTests` runs the C# card on the same state with",
         "`OracleScreen` and compares everything (the saved game through `OriginalSaves.Write`).", "",
         "## Totals", "",
         "| | |", "|---|---|",
         "| cards | %d |" % len(cards),
         "| runs | %d (%d per card: options 0..9 x location 3/120 x plain/probe) |" % (runs, runs // max(1, len(cards))),
         "| runs the original does not finish | %d |" % stops,
         "| runs the C# agrees with | %d (%s) |" % (agree, pct(agree, runs)),
         "| runs that differ for a listed reason (card-divergences.json) | %d |" % justified,
         "| runs that differ | %d |" % differ,
         "| cards whose every run agrees (or differs for a listed reason) | %d of %d |" % (full, len(cards)),
         "| blocks of the card records exercised | %d/%d (%s) |" % (rb[0], rb[1], pct(rb[0], rb[1])),
         "| branch outcomes of the card records exercised | %d/%d (%s) |" % (rb[2], rb[3], pct(rb[2], rb[3])),
         "", "## Listed differences", ""]
    for d in divergences:
        L.append("- card %s, %s: `%s` — %s" % (d["card"], "every run" if d["run"] == "*" else d["run"], d["contains"], d["why"]))
    L += ["", "## Per card", "",
          "Coverage is of the card's whole record (records with several cards count once per card).", "",
          "| card | function | record | agree | listed | differ | blocks | outcomes | first difference |",
          "|---|---|---|---|---|---|---|---|---|"]
    for k in sorted(cards):
        v = cards[k]
        rp = replay.get(k, {"agree": 0, "justified": 0, "differ": len(v["runs"]), "first": "not replayed"})
        c = cover[v["record"]]
        L.append("| %s | %s | %s | %d | %d | %d | %d/%d | %d/%d | %s |" % (
            k, v["function"], v["record"], rp["agree"], rp["justified"], rp["differ"], c[0], c[1], c[2], c[3],
            rp["first"].replace("|", "\\|")[:200]))
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("cards", len(cards), "agree", agree, "listed", justified, "differ", differ)


if __name__ == "__main__":
    main()
