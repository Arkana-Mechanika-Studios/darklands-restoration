using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Xunit.Abstractions;

namespace Darklands.Architecture.Tests;

/// <summary>
/// Report-only scan for string literals that are probably player-visible English in the game projects. It never fails on the counts;
/// it fails only when the sources cannot be found. Once the strings have moved to message ids this becomes a failing guard (the
/// counts then have to stay at, or fall to, a recorded ceiling per project). The result goes to the test output and to
/// "visible-text-report.txt" in the test's output folder.
/// </summary>
public sealed partial class VisibleTextReportTests(ITestOutputHelper output)
{
    private static readonly string[] Projects = ["Darklands.Core", "Darklands.Cards", "Darklands.Simulation", "Darklands.Presentation"];

    /// <summary>A path or namespace segment that marks diagnostics-only code.</summary>
    private static readonly string[] DiagnosticsMarks = ["Diagnostics", "Tracing", "Trace", "Oracle", "Debug"];

    /// <summary>Calls whose string arguments are for developers, not players.</summary>
    private static readonly string[] DeveloperReceivers = ["Debug", "Trace", "Debugger", "Contract", "Log", "Logger", "_logger", "logger", "Console", "Assert"];

    [GeneratedRegex(@"[A-Za-z]{3,}")]
    private static partial Regex LetterRun();

    // a lone capitalised word ("Endurance"); PascalCase identifiers such as card class names do not match
    [GeneratedRegex(@"^[A-Z][a-z]{2,}\.?$")]
    private static partial Regex CapitalWord();

    [GeneratedRegex(@"\{[^{}]*\}|%[-+ #0]*\d*(\.\d+)?[a-zA-Z]")]
    private static partial Regex FormatHole();

    [GeneratedRegex(@"^[\w\-\\/:. ]*\.[A-Za-z0-9]{1,4}$")]
    private static partial Regex FileName();

    [Fact]
    public void ReportLikelyVisibleText()
    {
        var root = FindRoot();
        var totals = new List<(string Project, int Count, int Files)>();
        var details = new StringBuilder();

        foreach (var project in Projects)
        {
            var directory = Path.Combine(root, "src", project);
            Assert.True(Directory.Exists(directory), $"sources of {project} not found at {directory}");
            var files = Directory.EnumerateFiles(directory, "*.cs", SearchOption.AllDirectories)
                .Where(f => !IsBuildOutput(directory, f))
                .Order(StringComparer.Ordinal)
                .ToArray();
            Assert.NotEmpty(files);

            var perFile = new List<(string File, List<(int Line, string Text)> Sites)>();
            foreach (var file in files)
            {
                var sites = Scan(file);
                if (sites.Count > 0)
                {
                    perFile.Add((Path.GetRelativePath(directory, file).Replace('\\', '/'), sites));
                }
            }
            totals.Add((project, perFile.Sum(f => f.Sites.Count), perFile.Count));

            details.AppendLine().AppendLine($"== {project} ==");
            foreach (var (file, sites) in perFile.OrderByDescending(f => f.Sites.Count).ThenBy(f => f.File, StringComparer.Ordinal))
            {
                details.AppendLine($"{sites.Count,5}  {file}");
                foreach (var (line, text) in sites)
                {
                    details.AppendLine($"         {line}: {Shorten(text)}");
                }
            }
        }

        var report = new StringBuilder();
        report.AppendLine("Likely player-visible string literals (heuristic, report only)");
        foreach (var (project, count, files) in totals)
        {
            report.AppendLine($"{project,-24} {count,6} sites in {files,3} files");
        }
        report.AppendLine($"{"total",-24} {totals.Sum(t => t.Count),6}");
        report.Append(details);

        var summary = report.ToString();
        output.WriteLine(summary);
        File.WriteAllText(Path.Combine(AppContext.BaseDirectory, "visible-text-report.txt"), summary);
    }

    private static List<(int Line, string Text)> Scan(string file)
    {
        var sites = new List<(int, string)>();
        var source = File.ReadAllText(file);
        if (source.AsSpan(0, Math.Min(source.Length, 400)).Contains("<auto-generated", StringComparison.Ordinal))
        {
            return sites;
        }
        var tree = CSharpSyntaxTree.ParseText(source, path: file);

        foreach (var node in tree.GetRoot().DescendantNodes())
        {
            string? text = node switch
            {
                LiteralExpressionSyntax l when l.IsKind(SyntaxKind.StringLiteralExpression) => l.Token.ValueText,
                InterpolatedStringExpressionSyntax i => InterpolatedText(i),
                _ => null,
            };
            if (text is null || !LooksVisible(text) || IsExcludedContext(node))
            {
                continue;
            }
            sites.Add((tree.GetLineSpan(node.Span).StartLinePosition.Line + 1, text));
        }
        return sites;
    }

    /// <summary>The fixed parts of an interpolated string with {} for each hole.</summary>
    private static string InterpolatedText(InterpolatedStringExpressionSyntax node)
    {
        var sb = new StringBuilder();
        foreach (var part in node.Contents)
        {
            sb.Append(part is InterpolatedStringTextSyntax t ? t.TextToken.ValueText : "{}");
        }
        return sb.ToString();
    }

    private static bool LooksVisible(string text)
    {
        var fixedPart = FormatHole().Replace(text, " ").Trim();
        if (!LetterRun().IsMatch(fixedPart))
        {
            return false;
        }
        var hasSpace = fixedPart.Any(char.IsWhiteSpace);
        if (!hasSpace && !CapitalWord().IsMatch(fixedPart))
        {
            return false;
        }
        if (!hasSpace && (fixedPart.Contains('_') || fixedPart.Contains('/') || fixedPart.Contains('\\')))
        {
            return false;
        }
        return !FileName().IsMatch(fixedPart);
    }

    private static bool IsExcludedContext(SyntaxNode node)
    {
        // a string that is only the operand of another literal in a nested interpolation hole is still scanned on its own
        for (var current = node.Parent; current is not null; current = current.Parent)
        {
            switch (current)
            {
                case AttributeSyntax:
                case ThrowStatementSyntax:
                case ThrowExpressionSyntax:
                case CaseSwitchLabelSyntax:
                case CasePatternSwitchLabelSyntax:
                    return true;
                case ObjectCreationExpressionSyntax create when create.Type.ToString().EndsWith("Exception", StringComparison.Ordinal):
                    return true;
                case ImplicitObjectCreationExpressionSyntax { Parent: ThrowExpressionSyntax or ThrowStatementSyntax }:
                    return true;
                case InvocationExpressionSyntax call when IsDeveloperCall(call):
                    return true;
                case NamespaceDeclarationSyntax ns when HasMark(ns.Name.ToString()):
                    return true;
                case FileScopedNamespaceDeclarationSyntax fns when HasMark(fns.Name.ToString()):
                    return true;
            }
        }
        return false;
    }

    private static bool IsDeveloperCall(InvocationExpressionSyntax call)
    {
        switch (call.Expression)
        {
            case IdentifierNameSyntax { Identifier.Text: "nameof" }:
                return true;
            case MemberAccessExpressionSyntax member:
                var receiver = member.Expression.ToString();
                var last = receiver.Split('.')[^1];
                var name = member.Name.Identifier.Text;
                return DeveloperReceivers.Contains(last)
                    || name.StartsWith("Log", StringComparison.Ordinal)
                    || name is "Fail" or "ThrowIf" or "ThrowIfNull" or "ThrowIfNullOrEmpty";
            default:
                return false;
        }
    }

    private static bool HasMark(string name) =>
        name.Split('.').Any(segment => DiagnosticsMarks.Contains(segment));

    private static bool IsBuildOutput(string projectDirectory, string file)
    {
        var relative = Path.GetRelativePath(projectDirectory, file).Replace('\\', '/');
        if (relative.StartsWith("obj/", StringComparison.Ordinal) || relative.StartsWith("bin/", StringComparison.Ordinal)
            || relative.EndsWith(".g.cs", StringComparison.Ordinal))
        {
            return true;
        }
        // a file or folder named for diagnostics is not player text
        return relative.Split('/').Any(segment =>
            DiagnosticsMarks.Any(m => segment.Equals(m, StringComparison.OrdinalIgnoreCase)
                || segment.Equals(m + ".cs", StringComparison.OrdinalIgnoreCase)));
    }

    private static string Shorten(string text)
    {
        var flat = text.Replace("\r", "\\r").Replace("\n", "\\n");
        return flat.Length <= 90 ? $"\"{flat}\"" : $"\"{flat[..87]}...\"";
    }

    private static string FindRoot()
    {
        for (var directory = new DirectoryInfo(AppContext.BaseDirectory); directory is not null; directory = directory.Parent)
        {
            if (File.Exists(Path.Combine(directory.FullName, "Darklands.slnx")))
            {
                return directory.FullName;
            }
        }
        throw new DirectoryNotFoundException("Darklands.slnx not found above " + AppContext.BaseDirectory);
    }
}
