namespace Darklands.Platform;

/// <summary>
/// An 8×16 text-mode font: 256 code page 437 characters of 16 rows, one byte per row (bit 7 the
/// leftmost dot), as the VGA BIOS keeps it.
/// </summary>
public sealed class TextFont
{
    public const int GlyphHeight = 16;
    public const int ByteLength = 256 * GlyphHeight;

    private readonly byte[] _rows;

    private TextFont(byte[] rows) => _rows = rows;

    public byte Row(byte character, int row) => _rows[character * GlyphHeight + row];

    /// <summary>
    /// A font dump supplied by the player (the VGA BIOS's or an emulator's 8×16 font): 4096 raw
    /// bytes, or the same in base64.
    /// </summary>
    public static TextFont Load(string path)
    {
        var bytes = File.ReadAllBytes(path);
        if (bytes.Length != ByteLength)
        {
            try
            {
                bytes = Convert.FromBase64String(System.Text.Encoding.ASCII.GetString(bytes).Trim());
            }
            catch (FormatException e)
            {
                throw new InvalidDataException($"{path} is neither a {ByteLength}-byte 8x16 font nor its base64.", e);
            }
        }
        if (bytes.Length != ByteLength)
        {
            throw new InvalidDataException($"{path} does not hold a {ByteLength}-byte 8x16 font.");
        }
        return new TextFont(bytes);
    }

    /// <summary>
    /// The font from the environment variable DARKLANDS_TEXT_FONT, if it names a readable font;
    /// otherwise <see cref="Fallback"/>.
    /// </summary>
    public static TextFont FromEnvironment(string? path = null)
    {
        path ??= Environment.GetEnvironmentVariable("DARKLANDS_TEXT_FONT");
        if (!string.IsNullOrWhiteSpace(path) && File.Exists(path))
        {
            try
            {
                return Load(path);
            }
            catch (InvalidDataException)
            {
            }
        }
        return Fallback;
    }

    /// <summary>
    /// The built-in font: the VGA 8×16 text font as DOSBox-X provides it (Resources/vga-8x16.b64, see
    /// THIRD_PARTY_NOTICES.md), the font the original's banner is shown in. If the resource cannot be
    /// read, simple 5×7 shapes of the printable ASCII and box-drawing characters stand in.
    /// </summary>
    public static TextFont Fallback => _fallback ??= LoadEmbedded() ?? BuildFallback();

    private static TextFont? LoadEmbedded()
    {
        using var stream = typeof(TextFont).Assembly.GetManifestResourceStream("Darklands.Platform.vga-8x16.b64");
        if (stream is null)
        {
            return null;
        }
        using var reader = new StreamReader(stream, System.Text.Encoding.ASCII);
        var bytes = Convert.FromBase64String(reader.ReadToEnd().Trim());
        return bytes.Length == ByteLength ? new TextFont(bytes) : null;
    }

    private static TextFont? _fallback;

    /// <summary>
    /// A row (0..7) of the built-in 8×8 glyph of a printable ASCII character, for text the BIOS
    /// writes on the graphics screen (its 8×8 font); 0 for other characters and rows.
    /// </summary>
    public static byte SmallRow(byte character, int row)
    {
        if (row is < 0 or >= 7)
        {
            return 0;
        }
        foreach (var (c, glyph) in Ascii)
        {
            if (c == character)
            {
                return (byte)(Convert.ToByte(glyph[row], 2) << 2);
            }
        }
        return 0;
    }

    private static TextFont BuildFallback()
    {
        var rows = new byte[ByteLength];
        foreach (var (character, glyph) in Ascii)
        {
            for (var y = 0; y < 7; y++)
            {
                // 5 dots in bits 6..2, widened by one dot (VGA glyphs have 2-dot vertical strokes), 2 rows per dot row
                var bits = Convert.ToByte(glyph[y], 2) << 2;
                var row = (byte)(bits | (bits >> 1));
                rows[character * GlyphHeight + 1 + 2 * y] = row;
                rows[character * GlyphHeight + 2 + 2 * y] = row;
            }
        }
        void Lines(int character, Func<int, byte> row)
        {
            for (var y = 0; y < GlyphHeight; y++)
            {
                rows[character * GlyphHeight + y] = row(y);
            }
        }
        // double lines: rows 6 and 9, columns 2 and 5; single lines: row 7, column 3
        Lines(0xCD, y => y is 6 or 9 ? (byte)0xFF : (byte)0);
        Lines(0xBA, _ => 0x24);
        Lines(0xC9, y => y < 6 ? (byte)0 : y == 6 ? (byte)0x3F : y < 9 ? (byte)0x20 : y == 9 ? (byte)0x27 : (byte)0x24);
        Lines(0xBB, y => y < 6 ? (byte)0 : y == 6 ? (byte)0xFC : y < 9 ? (byte)0x04 : y == 9 ? (byte)0xE4 : (byte)0x24);
        Lines(0xC8, y => y < 6 ? (byte)0x24 : y == 6 ? (byte)0x27 : y < 9 ? (byte)0x20 : y == 9 ? (byte)0x3F : (byte)0);
        Lines(0xBC, y => y < 6 ? (byte)0x24 : y == 6 ? (byte)0xE4 : y < 9 ? (byte)0x04 : y == 9 ? (byte)0xFC : (byte)0);
        Lines(0xC4, y => y == 7 ? (byte)0xFF : (byte)0);
        Lines(0xB3, _ => 0x10);
        Lines(0xDA, y => y < 7 ? (byte)0 : y == 7 ? (byte)0x1F : (byte)0x10);
        Lines(0xBF, y => y < 7 ? (byte)0 : y == 7 ? (byte)0xF0 : (byte)0x10);
        Lines(0xC0, y => y < 7 ? (byte)0x10 : y == 7 ? (byte)0x1F : (byte)0);
        Lines(0xD9, y => y < 7 ? (byte)0x10 : y == 7 ? (byte)0xF0 : (byte)0);
        Lines(0xB0, y => y % 4 == 0 ? (byte)0x88 : y % 4 == 2 ? (byte)0x22 : (byte)0);
        Lines(0xB1, y => y % 2 == 0 ? (byte)0xAA : (byte)0x55);
        Lines(0xB2, y => y % 4 == 0 ? (byte)0x77 : y % 4 == 2 ? (byte)0xDD : (byte)0xFF);
        Lines(0xDB, _ => 0xFF);
        return new TextFont(rows);
    }

